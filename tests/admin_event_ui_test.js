const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context={document:{addEventListener(){}},console};
vm.createContext(context);
const path=__dirname+'/../admin/assets/js/events.js';
assert.ok(fs.existsSync(path),'event UI module exists');
vm.runInContext(fs.readFileSync(path,'utf8'),context);
const base={supported:true,revision:4,desired_enabled:false,applied_enabled:false,status:'OFF',cleanup_jobs:[],heartbeat_at:'2026-10-08 00:00:00'};
assert.equal(context.eventCanToggle(base),true);
assert.equal(context.eventCanToggle({...base,supported:false}),false);
assert.equal(context.eventCanToggle({...base,desired_enabled:true}),false);
assert.equal(context.eventCanToggle({...base,cleanup_jobs:[{status:'pending'}]}),false);
assert.equal(context.eventCanToggle({...base,cleanup_jobs:[{status:'failed'}]}),false);
assert.equal(context.eventCanToggle({...base,cleanup_jobs:[{status:'completed'}]}),true);
assert.equal(context.eventCanToggle({...base,applied_enabled:true,desired_enabled:true,status:'ERROR',cleanup_jobs:[{status:'error'}]}),true,'cleanup error must not prevent disabling the active event');
assert.equal(context.eventCanToggle({...base,status:'CLEANUP_PENDING'}),false);
assert.match(context.eventStatus({...base,desired_enabled:true}),/Đang bật/);
assert.match(context.eventStatus({...base,status:'ERROR'}),/Lỗi/);
assert.match(context.eventDisableConfirmation({...base,name:'Summer',consumed_ids:[1,2],kept_ids:[3]}),/1, 2/);
assert.match(context.eventDisableConfirmation({...base,name:'Summer',consumed_ids:[1],kept_ids:[3]}),/Giữ.*3/);
console.log('event UI pending/unsupported/cleanup/permanent rewards OK');
